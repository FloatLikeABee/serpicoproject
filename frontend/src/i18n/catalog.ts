const catalogs: Record<Nation, Catalog> = { us: en, cn: zh };

export function t(nation: Nation, key: string, vars?: Record<string, string | number>): string {
  const table = catalogs[nation] || en;
  let out = table[key] || en[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return out;
}

